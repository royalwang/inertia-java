import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../..', import.meta.url))
const sample = resolve(root, 'examples/spring-react')
const template = resolve(root, 'docs/examples/first-application')
const target = process.argv[2] && resolve(process.argv[2])
if (!target || existsSync(target)) throw new Error('Usage: node docs/scripts/create-first-application.mjs /absolute/new-directory (must not exist)')
const repository = resolve(root, '..')
if (target === repository || target.startsWith(repository + '/')) throw new Error('Create the tutorial application outside the repository')
mkdirSync(target, { recursive: true })
cpSync(resolve(sample, 'src/main'), resolve(target, 'src/main'), { recursive: true })
cpSync(resolve(template, 'pom.xml'), resolve(target, 'pom.xml'))
for (const name of ['LICENSE', 'NOTICE']) cpSync(resolve(root, name), resolve(target, name))
cpSync(resolve(template, 'HelloController.java'), resolve(target, 'src/main/java/io/inertia/example/HelloController.java'))
const application = resolve(target, 'src/main/java/io/inertia/example/Application.java')
const code = readFileSync(application, 'utf8')
if (!code.includes('"Users/Index",')) throw new Error('Sample component registry changed; update tutorial')
writeFileSync(application, code.replace('"Users/Index",', '"Hello",\n            "Users/Index",'))
const frontend = resolve(target, 'frontend')
mkdirSync(resolve(frontend, 'scripts'), { recursive: true })
for (const name of ['package.json', 'package-lock.json', 'tsconfig.json', 'vite.config.ts']) cpSync(resolve(sample, 'frontend', name), resolve(frontend, name))
cpSync(resolve(sample, 'frontend/src'), resolve(frontend, 'src'), { recursive: true })
for (const name of ['build.mjs', 'release-assets.mjs']) cpSync(resolve(sample, 'frontend/scripts', name), resolve(frontend, 'scripts', name))
// Include only commands whose inputs were copied. Browser acceptance is owned by docs tooling.
const packageFile = resolve(frontend, 'package.json')
const pkg = JSON.parse(readFileSync(packageFile, 'utf8'))
pkg.scripts = Object.fromEntries(['dev', 'build', 'typecheck', 'ssr'].map(key => [key, pkg.scripts[key]]))
writeFileSync(packageFile, JSON.stringify(pkg, null, 2) + '\n')
cpSync(resolve(template, 'Hello.tsx'), resolve(frontend, 'src/pages/Hello.tsx'))
const pages = resolve(frontend, 'src/pages.ts')
const registry = readFileSync(pages, 'utf8')
if (!registry.includes('const pages = { Advanced,')) throw new Error('Client registry changed; update tutorial')
writeFileSync(pages, "import Hello from './pages/Hello'\n" + registry.replace('const pages = { Advanced,', 'const pages = { Hello, Advanced,'))
writeFileSync(resolve(target, '.gitignore'), 'target/\nfrontend/node_modules/\nfrontend/dist/\nfrontend/.inertia/\n')
console.log('Created independent Maven application: ' + target)
